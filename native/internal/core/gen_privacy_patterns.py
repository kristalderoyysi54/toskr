"""从 Tauri privacy.rs（及 privacy/context.rs、privacy/providers.rs）按 OnceLock 名抽出内建正则，生成 privacy_patterns_gen.go。

直接搬原文而不是手抄：规则里有大量字符类，手抄易错；Tauri 规则更新后重跑 `go generate ./internal/core` 即同步。
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[3] / "src-tauri" / "src"
files = [root / "privacy.rs", root / "privacy" / "context.rs", root / "privacy" / "providers.rs"]
src = "\n".join(f.read_text(encoding="utf-8") for f in files)
cell = re.compile(r'&([A-Z][A-Z0-9_]*),\s*(?://[^\n]*\n\s*)*r(#*)"')
out = {}
for m in cell.finditer(src):
    start = m.end()
    out[m.group(1)] = src[start:src.index('"' + m.group(2), start)]
lines = ["// Code generated by gen_privacy_patterns.py from src-tauri/src/privacy*.rs; DO NOT EDIT.", "", "package core", "",
         "var tauriPatterns = map[string]string{"]
for k in sorted(out):
    lines.append(f"\t{json.dumps(k)}: {json.dumps(out[k], ensure_ascii=False)},")
lines += ["}", ""]
(pathlib.Path(__file__).parent / "privacy_patterns_gen.go").write_text("\n".join(lines), encoding="utf-8")
print(len(out), "patterns")
